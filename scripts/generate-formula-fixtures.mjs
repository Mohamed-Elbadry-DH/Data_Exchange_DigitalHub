/**
 * Generate minimal P0 formula fixtures with ExcelJS.
 * Run: node scripts/generate-formula-fixtures.mjs
 */
import ExcelJS from "exceljs";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(__dirname, "../tests/excel-formulas");
fs.mkdirSync(outDir, { recursive: true });

async function write(name, build) {
  const wb = new ExcelJS.Workbook();
  const ws = wb.addWorksheet("Sheet1");
  build(ws);
  const file = path.join(outDir, name);
  await wb.xlsx.writeFile(file);
  console.log("wrote", name);
}

await write("01-basic-arithmetic.xlsx", (ws) => {
  ws.getCell("B8").value = 100;
  ws.getCell("C8").value = 200;
  ws.getCell("D8").value = { formula: "B8+C8", result: 300 };
});

await write("02-sum-ranges.xlsx", (ws) => {
  for (let r = 8; r <= 12; r++) ws.getCell(`B${r}`).value = r;
  ws.getCell("D8").value = { formula: "SUM(B8:B12)", result: 50 };
});

await write("03-percentage.xlsx", (ws) => {
  ws.getCell("B8").value = 200;
  ws.getCell("C8").value = { formula: "B8*10%", result: 20 };
});

await write("04-if.xlsx", (ws) => {
  ws.getCell("B8").value = 50;
  ws.getCell("C8").value = { formula: 'IF(B8>=50,"OK","NO")', result: "OK" };
});

await write("05-formula-chain.xlsx", (ws) => {
  ws.getCell("B8").value = 100;
  ws.getCell("C8").value = { formula: "B8*0.1", result: 10 };
  ws.getCell("D8").value = { formula: "B8+C8", result: 110 };
  ws.getCell("E8").value = { formula: "D8/10", result: 11 };
});

await write("06-absolute-reference.xlsx", (ws) => {
  ws.getCell("A1").value = 2;
  ws.getCell("B8").value = 10;
  ws.getCell("C8").value = { formula: "B8*$A$1", result: 20 };
});

await write("07-circular-reference.xlsx", (ws) => {
  ws.getCell("A1").value = { formula: "B1" };
  ws.getCell("B1").value = { formula: "A1" };
});

await write("08-div-zero.xlsx", (ws) => {
  ws.getCell("B8").value = 0;
  ws.getCell("D8").value = { formula: "100/B8" };
});

await write("09-multiple-formulas.xlsx", (ws) => {
  ws.getCell("B8").value = 10;
  ws.getCell("C8").value = 20;
  ws.getCell("D8").value = { formula: "SUM(B8:C8)", result: 30 };
  ws.getCell("E8").value = { formula: "AVERAGE(B8:C8)", result: 15 };
  ws.getCell("F8").value = { formula: "MAX(B8:C8)", result: 20 };
  ws.getCell("G8").value = { formula: "MIN(B8:C8)", result: 10 };
});

await write("10-complex-calculation.xlsx", (ws) => {
  ws.getCell("B8").value = 100;
  ws.getCell("C8").value = 50;
  ws.getCell("D8").value = { formula: "ROUND((B8+C8)*0.15,2)", result: 22.5 };
  ws.getCell("E8").value = { formula: "IFERROR(D8/B8,0)", result: 0.225 };
});

await write("11-formula-with-empty-input.xlsx", (ws) => {
  ws.getCell("D8").value = { formula: "B8+C8", result: 0 };
});

await write("12-negative-decimals.xlsx", (ws) => {
  ws.getCell("B8").value = -3.5;
  ws.getCell("C8").value = 1.25;
  ws.getCell("D8").value = { formula: "B8*C8", result: -4.375 };
});

await write("13-zero-values.xlsx", (ws) => {
  ws.getCell("B8").value = 0;
  ws.getCell("C8").value = 0;
  ws.getCell("D8").value = { formula: "B8+C8", result: 0 };
});

await write("14-formula-error-recovery.xlsx", (ws) => {
  ws.getCell("B8").value = 0;
  ws.getCell("D8").value = { formula: "100/B8" };
});

await write("15-multi-level-chain.xlsx", (ws) => {
  ws.getCell("A1").value = 2;
  ws.getCell("B1").value = { formula: "A1*3", result: 6 };
  ws.getCell("C1").value = { formula: "B1+4", result: 10 };
  ws.getCell("D1").value = { formula: "C1*5", result: 50 };
  ws.getCell("E1").value = { formula: "ABS(D1-100)", result: 50 };
});

await write("16-large-dependency-graph.xlsx", (ws) => {
  for (let i = 1; i <= 30; i++) {
    ws.getCell(i, 1).value = i;
  }
  ws.getCell("B1").value = { formula: "SUM(A1:A30)", result: 465 };
  ws.getCell("B2").value = { formula: "AVERAGE(A1:A30)", result: 15.5 };
  ws.getCell("B3").value = { formula: "B1+B2", result: 480.5 };
});

fs.writeFileSync(
  path.join(outDir, "README.md"),
  `# Excel formula fixtures (P0)

Generated by \`node scripts/generate-formula-fixtures.mjs\`.

Headless acceptance: \`node scripts/test-calculation-p0.mjs\`

Profile: \`P0-v1\` (SUM AVERAGE MIN MAX COUNT ROUND ABS IF IFERROR).
`,
);

console.log("done");
